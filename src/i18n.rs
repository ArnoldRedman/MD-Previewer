#[derive(Copy, Clone)]
pub(crate) enum Lang {
    Zh,
    En,
}

pub(crate) fn detect_lang() -> Lang {
    sys_locale::get_locale()
        .map(|l| {
            if l.to_lowercase().starts_with("zh") {
                Lang::Zh
            } else {
                Lang::En
            }
        })
        .unwrap_or(Lang::En)
}

